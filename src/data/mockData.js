// ---------- Registration Trend Data ----------
export const generateRegistrationTrend = () => {
  const data = [];
  const now = new Date();
  for (let i = 29; i >= 0; i--) {
    const date = new Date(now);
    date.setDate(date.getDate() - i);
    const label = date.toLocaleDateString('en-IN', { month: 'short', day: 'numeric' });
    const base = 15 + Math.floor(Math.random() * 25);
    data.push({
      date: label,
      registrations: base + (i < 7 ? Math.floor(Math.random() * 20) : 0),
      events: i % 5 === 0 ? 1 : 0,
    });
  }
  return data;
};

