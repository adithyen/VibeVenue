export const getDashboardStats = (events) => {
  const upcoming = events.filter(e => e.status === 'upcoming').length;
  const totalRegs = events.reduce((sum, e) => sum + e.registrationCount, 0);
  const totalSeats = events.reduce((sum, e) => sum + e.maxParticipants, 0);
  const available = totalSeats - totalRegs;
  return {
    totalEvents: events.length,
    upcomingEvents: upcoming,
    totalRegistrations: totalRegs,
    availableSeats: Math.max(0, available),
  };
};

export const getRecentRegistrations = (events, limit = 10) => {
  const all = events.flatMap(evt =>
    evt.participants.map(p => ({
      ...p,
      eventName: evt.name,
      eventCategory: evt.category,
    }))
  );
  return all
    .sort((a, b) => new Date(b.registeredAt) - new Date(a.registeredAt))
    .slice(0, limit);
};

